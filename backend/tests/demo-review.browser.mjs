import assert from 'node:assert/strict'
import {mkdirSync} from 'node:fs'
import {chromium} from '@playwright/test'
import {demoReviews} from '../demo/review-scenarios.mjs'

const frontend=process.env.BASIS_FRONTEND_URL
assert.equal(frontend,'http://127.0.0.1:8842/app')
assert.ok(process.env.BASIS_STATE_DIR?.includes('/verification/run-browser-'))
const api=new URL('/local-api/v1',frontend).href
const scenario=demoReviews[0]
assert.equal((await(await fetch(new URL('/local-api/health',frontend))).json()).generationPolicy,'demo')
const browser=await chromium.launch({headless:true})
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}})
 page.setDefaultTimeout(30000)
 const errors=[];page.on('pageerror',error=>errors.push(error.message))
 await page.goto(frontend+'/#project/'+scenario.projectId)
 await page.getByRole('button',{name:'New query',exact:true}).click()
 await page.locator('#query').fill(scenario.question)
 const posted=page.waitForResponse(response=>response.url().endsWith('/projects/'+scenario.projectId+'/queries')&&response.request().method()==='POST')
 await page.locator('.run-query').click()
 const job=await(await posted).json()
 const report=page.getByRole('article',{name:'Query report'})
 await page.waitForFunction(()=>/1\.5(?:0)?\s*m[³3]\/s/.test(document.querySelector('.query-report')?.textContent||''),{},{timeout:120000})
 const completed=await(await fetch(api+'/projects/'+scenario.projectId+'/queries/'+job.id)).json()
 assert.equal(completed.state,'completed');assert.equal(completed.result.mode,'verified_review')
 assert.equal(completed.result.arithmeticReview?.applicabilityConfirmed,false)
 assert.match(await report.innerText(),/0\.6(?:0)?\s*m[³3]\/s/)
 assert.match(await report.innerText(),/computer.*modell|modelling.*computer/i)
 assert.doesNotMatch(await report.innerText(),/necessitating an upgrade/i)
 for(const documentId of scenario.requiredDocumentIds){
  const source=completed.result.references.find(reference=>reference.doc===documentId)
  assert.ok(source,'Missing original engineering evidence '+documentId)
  await page.getByRole('button',{name:new RegExp('^Source '+source.id+':')}).first().click()
  await page.locator('.source-highlight:visible').first().waitFor()
  await page.waitForFunction(()=>document.querySelectorAll('.pdf-status').length===0)
 }
 const saved=await fetch(api+'/projects/'+scenario.projectId+'/queries/'+job.id,{method:'PATCH',headers:{'Content-Type':'application/json'},body:JSON.stringify({saved:true})})
 assert.ok(saved.ok)
 await page.goto(frontend+'/#project/'+scenario.projectId)
 const history=page.getByRole('region',{name:'Project query history'})
 await history.getByRole('button',{name:'Saved',exact:true}).click()
 await history.getByRole('link',{name:new RegExp('A subdivision has expanded')}).click()
 await report.waitFor();assert.match(await report.innerText(),/0\.6(?:0)?\s*m[³3]\/s/)
 await page.reload();await report.waitFor()
 assert.match(await report.innerText(),/1\.5(?:0)?\s*m[³3]\/s/)
 await page.getByRole('button',{name:new RegExp('^Source '+completed.result.references[0].id+':')}).first().click()
 await page.waitForFunction(()=>document.querySelectorAll('.pdf-status').length===0)
 await page.locator('.source-highlight:visible').first().waitFor()
 mkdirSync('test-results',{recursive:true})
 await page.screenshot({path:'test-results/demo-capacity-sources.png',fullPage:true})
 await page.locator('.requirements-review summary').click()
 assert.match(await page.locator('.requirements-review').innerText(),/0\.6 m³\/s shortfall/)
 await page.getByRole('button',{name:'Inspect check source 1',exact:true}).first().click()
 await page.locator('.source-highlight:visible').first().waitFor()
 const exported=page.waitForEvent('popup')
 await page.getByRole('button',{name:'Export review',exact:true}).click()
 const brief=await exported
 await brief.getByRole('heading',{name:'Source register',exact:true}).waitFor()
 assert.match(await brief.locator('body').innerText(),/0\.6 m³\/s shortfall/)
 assert.ok((await brief.locator('body').innerText()).includes(scenario.question))
 await brief.emulateMedia({media:'print'})
 await brief.pdf({path:'test-results/engineering-review-brief.pdf',format:'A4',printBackground:true})
 await brief.close()
 await page.locator('.capacity-inputs summary').click()
 await page.getByLabel('Catchment area (ha)',{exact:true}).fill('30')
 assert.ok(await page.getByRole('button',{name:'Run revised capacity check',exact:true}).isDisabled())
 await page.getByLabel('Catchment area (ha)',{exact:true}).fill('55')
 await page.getByLabel('Five-year runoff',{exact:true}).fill('1600')
 await page.getByLabel('Runoff unit',{exact:true}).selectOption('L/s')
 const assumptionPost=page.waitForResponse(response=>response.url().endsWith('/projects/'+scenario.projectId+'/queries')&&response.request().method()==='POST')
 await page.getByRole('button',{name:'Run revised capacity check',exact:true}).click()
 const assumptionJob=await(await assumptionPost).json()
 assert.notEqual(assumptionJob.id,job.id)
 await page.waitForFunction(()=>/1\.1(?:0)?\s*m[³3]\/s/.test(document.querySelector('.query-report')?.textContent||''),{},{timeout:30000})
 const assumptionResult=await(await fetch(api+'/projects/'+scenario.projectId+'/queries/'+assumptionJob.id)).json()
 assert.deepEqual(assumptionResult.result.arithmeticReview.calculations.map(step=>step.value),[2,1.1])
 assert.deepEqual(assumptionResult.documentIds.slice().sort(),completed.documentIds.slice().sort())
 const original=await(await fetch(api+'/projects/'+scenario.projectId+'/queries/'+job.id)).json()
 assert.deepEqual(original.result.arithmeticReview.calculations.map(step=>step.value),[1.5,.6])
 await page.goto(frontend+'/#project/'+scenario.projectId+'/query/'+job.id)
 await report.waitFor()
 await page.getByRole('button',{name:'Expand result panel',exact:true}).click()
 await page.screenshot({path:'test-results/demo-capacity-review.png',fullPage:true})
 // An unrehearsed numerical revision must be recalculated through the real UI.
 await page.goto(frontend+'/#project/'+scenario.projectId)
 await page.getByRole('button',{name:'New query',exact:true}).click()
 await page.locator('#query').fill(scenario.question.replace('42 ha','55 ha').replace('1.20 m³/s','1600 L/s'))
 const revisedPost=page.waitForResponse(response=>response.url().endsWith('/projects/'+scenario.projectId+'/queries')&&response.request().method()==='POST')
 await page.locator('.run-query').click()
 const revisedJob=await(await revisedPost).json()
 await page.waitForFunction(()=>/1\.1(?:0)?\s*m[³3]\/s/.test(document.querySelector('.query-report')?.textContent||''),{},{timeout:30000})
 const revised=await(await fetch(api+'/projects/'+scenario.projectId+'/queries/'+revisedJob.id)).json()
 assert.equal(revised.result.mode,'verified_review')
 assert.deepEqual(revised.result.arithmeticReview.calculations.map(step=>step.value),[2,1.1])
 assert.match(await report.innerText(),/1600 L\/s/)
 await page.locator('#query').fill('Review storm sewer capacity and detention pond sizing for a 55 ha catchment. Existing sewer capacity: 900 L/s. Is the Rational Method suitable?')
 const missingPost=page.waitForResponse(response=>response.url().endsWith('/projects/'+scenario.projectId+'/queries')&&response.request().method()==='POST')
 await page.locator('.run-query').click()
 const missingJob=await(await missingPost).json()
 await page.getByText(/Five-year runoff estimate \(m³\/s or L\/s\)/).first().waitFor()
 const missing=await(await fetch(api+'/projects/'+scenario.projectId+'/queries/'+missingJob.id)).json()
 assert.equal(missing.result.mode,'insufficient_evidence')
 assert.deepEqual(missing.result.requiredInputs.fields.map(field=>field.key),['fiveYearRunoff'])
 assert.equal(missing.result.references.length,0)
 await page.screenshot({path:'test-results/capacity-inputs-required.png',fullPage:true})
 await page.locator('#query').fill('Review storm sewer capacity and detention pond sizing for a 55 ha catchment. Five-year runoff: 1600 L/s. Existing sewer capacity: 900 L/s. Is the Rational Method suitable?')
 const naturalPost=page.waitForResponse(response=>response.url().endsWith('/projects/'+scenario.projectId+'/queries')&&response.request().method()==='POST')
 await page.locator('.run-query').click()
 const naturalJob=await(await naturalPost).json()
 await page.waitForFunction(()=>/1\.1(?:0)?\s*m[³3]\/s/.test(document.querySelector('.query-report')?.textContent||''),{},{timeout:30000})
 const natural=await(await fetch(api+'/projects/'+scenario.projectId+'/queries/'+naturalJob.id)).json()
 assert.equal(natural.result.mode,'verified_review')
 assert.deepEqual(natural.result.arithmeticReview.calculations.map(step=>step.value),[2,1.1])
 assert.equal(natural.result.reviewInputs.fiveYearRunoff.baseValue,1.6)
 assert.doesNotMatch(await report.innerText(),/undefined/)
 assert.deepEqual(errors,[])
 console.log('PASS capacity review and source highlights, Saved/reload, numerical revision, precise missing-input guidance and a paraphrased engineering review')
}finally{await browser.close()}
