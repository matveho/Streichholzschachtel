import assert from 'node:assert/strict'
import {mkdirSync} from 'node:fs'
import {chromium} from '@playwright/test'

const frontend=process.env.BASIS_FRONTEND_URL
assert.equal(frontend,'http://127.0.0.1:8842/app')
assert.ok(process.env.BASIS_STATE_DIR?.includes('/verification/run-browser-'))
const base=new URL('/local-api/v1/projects/parkview-exchange',frontend).href
const browser=await chromium.launch({headless:true})
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}})
 page.setDefaultTimeout(30000)
 const before=await(await fetch(base)).json()
 const dynamic=before.issues.filter(issue=>!issue.prepared)
 assert.ok(dynamic.length>=13)
 const issue=dynamic.find(issue=>issue.status==='open')
 assert.ok(issue)
 await page.goto(frontend+'/#project/parkview-exchange')
 const panel=page.getByRole('region',{name:'Potential issues',exact:true})
 const card=()=>panel.locator('.project-issue').filter({has:page.getByText(issue.explanation,{exact:true})})
 await card().locator(':scope > summary').click()
 assert.match(await card().innerText(),/Review this potential discrepancy/)
 const dismissal=page.waitForResponse(r=>r.url().endsWith('/issues/'+issue.id)&&r.request().method()==='PATCH')
 await card().getByRole('button',{name:'Dismiss',exact:true}).click()
 assert.ok((await dismissal).ok())
 const scanned=page.waitForResponse(r=>r.url().endsWith('/rescan')&&r.request().method()==='POST')
 await panel.getByRole('button',{name:'Rescan',exact:true}).click()
 const rescan=await(await scanned).json()
 assert.deepEqual(rescan.issues.filter(i=>!i.prepared).map(i=>i.id).sort(),dynamic.map(i=>i.id).sort())
 assert.equal(rescan.issues.find(i=>i.id===issue.id).status,'dismissed')
 await page.reload()
 await panel.getByRole('button',{name:/^Dismissed /}).click()
 await card().locator(':scope > summary').click()
 const restored=page.waitForResponse(r=>r.url().endsWith('/issues/'+issue.id)&&r.request().method()==='PATCH')
 await card().getByRole('button',{name:'Restore',exact:true}).click()
 assert.ok((await restored).ok())
 const after=await(await fetch(base)).json()
 assert.equal(after.issues.find(i=>i.id===issue.id).status,'open')
 const model=page.getByRole('link',{name:'Download IFC model for Parkview Exchange Redevelopment'}).first()
 const modelUrl=await model.getAttribute('href')
 assert.ok(modelUrl)
 const downloaded=await page.request.get(new URL(modelUrl,frontend).href)
 assert.ok(downloaded.ok());assert.match(await downloaded.text(),/ISO-10303-21;/)
 await panel.getByRole('button',{name:/^Open /}).click()
 await card().locator(':scope > summary').click()
 mkdirSync('test-results',{recursive:true})
 await page.screenshot({path:'test-results/ifc-rescan-browser.png',fullPage:true})
 console.log('PASS real issues window, rescan, stable finding identities, dismissal after reload, restore and original IFC download')
} finally {await browser.close()}
