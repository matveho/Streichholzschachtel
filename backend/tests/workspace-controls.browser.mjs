import { chromium, expect } from '@playwright/test'
import assert from 'node:assert/strict'
import { resolve } from 'node:path'
const origin=process.env.BASIS_FRONTEND_URL
assert.equal(origin,'http://127.0.0.1:8842/app')
assert.ok(process.env.BASIS_STATE_DIR?.includes('/verification/run-browser-'))
const browser=await chromium.launch({headless:true})
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}})
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto(origin+'/#project/demo-mill-creek')
 const panel=page.getByRole('region',{name:'Project documents',exact:true})
 await panel.waitFor()
 assert.equal(await page.title(),'basis')
 assert.equal(await page.locator('.app-header strong').innerText(),'basis')
 assert.equal(await page.locator('.project-header .project-header-title').count(),0)
 assert.equal(await page.locator('.project-collection-summary').count(),0)
 const tabs=page.getByRole('navigation',{name:'Open queries'})
 assert.equal(await tabs.locator('.query-tab').first().innerText(),'Project dashboard')
 await page.getByRole('button',{name:'Open new query tab',exact:true}).click()
 await page.locator('#query').fill('150 mm sanitary sewer minimum slope')
 await tabs.getByRole('link',{name:'Project dashboard',exact:true}).click()
 await panel.waitFor()
 await tabs.getByRole('button',{name:'Query 1',exact:true}).click()
 assert.equal(await page.locator('#query').inputValue(),'150 mm sanitary sewer minimum slope')
 await tabs.getByRole('link',{name:'Project dashboard',exact:true}).click()
 await tabs.getByRole('button',{name:'Close Query 1',exact:true}).click()
 await panel.waitFor()
 assert.equal(await tabs.locator('.query-tab').count(),1)
 const count=await page.locator('.project-document-row').count()
 await panel.getByRole('button',{name:'Upload documents',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'Upload documents',exact:true})
 await dialog.waitFor()
 assert.equal(await dialog.getByRole('textbox',{name:'Project name',exact:true}).count(),0)
 await dialog.getByLabel('Add PDF files', {exact:true}).setInputFiles(resolve('backend/output/pdf/willow-creek-client-brief.pdf'))
 await dialog.getByRole('button',{name:'Upload and index',exact:true}).click()
 await dialog.waitFor({state:'hidden',timeout:60000})
 await expect(page.locator('.project-document-row')).toHaveCount(count+1)
 assert.equal(await page.getByText(/Not what you meant|This example project is read-only/).count(),0)
 assert.deepEqual(errors,[])
 console.log('PASS lowercase branding, persistent first dashboard tab, draft retention, closing queries on dashboard, simplified dashboard and upload to protected project')
} finally {await browser.close()}
